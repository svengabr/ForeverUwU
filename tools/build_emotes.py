"""Writes Emotes.lua: the game's own emote texts as Lua patterns, per locale.

CHAT_MSG_TEXT_EMOTE only carries the finished text ("Bob roars with bestial
vigor.  So fierce!") in the client's language, no emote token. So the addon
matches the text against every form of the emote (alone, at you, at someone,
your own) as the game writes it. The texts come from the client's
EmotesTextData table via wago.tools (the WoW: Forever client sits in the
wow_classic_beta product there).

EMOTES maps the game's emote names to the clip folder under raw/<set>/emote/
that plays for them; /lol, /rawr and /congrats are only other commands for
LAUGH, ROAR and CONGRATULATE.

Usage:  python tools/build_emotes.py
Needs network access to wago.tools.
"""

import csv
import io
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Emotes.lua"
PRODUCT = "wow_classic_beta"
LOCALES = ("enUS", "deDE", "esES", "esMX", "frFR", "itIT", "koKR", "ptBR", "ruRU", "zhCN", "zhTW")
EMOTES = {
    "SPIT": "spit",
    "ROAR": "roar",
    "LAUGH": "laugh",
    "GIGGLE": "laugh",
    "CHEER": "cheer",
    "CONGRATULATE": "cheer",
    "FLIRT": "flirt",
    "KISS": "kiss",
    "CRY": "cry",
    "NO": "no",
}
URL = "https://wago.tools/db2/{table}/csv?product=" + PRODUCT + "{locale}"


def fetch(table, locale=None):
    url = URL.format(table=table, locale=f"&locale={locale}" if locale else "")
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        text = response.read().decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


def pattern(template):
    """'%s cries on %s's shoulder.' -> '^.+%s+cries%s+on%s+.+'s%s+shoulder%.$'"""
    marked = re.sub(r"%(\d+\$)?s", "\0", template)
    escaped = re.sub(r"([\^$()%.\[\]*+\-?])", r"%\1", marked)
    # Some texts hold two spaces after a full stop; any run of spaces will do.
    spaced = re.sub(r" +", "%s+", escaped)
    return "^" + spaced.replace("\0", ".+") + "$"


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = {row["ID"]: row["Name"] for row in fetch("EmotesText")}
    missing = set(EMOTES) - set(names.values())
    if missing:
        sys.exit(f"emotes not in EmotesText: {', '.join(sorted(missing))}")

    lines = [
        "-- Generated by tools/build_emotes.py, don't edit by hand.",
        "-- Per locale: the game's emote texts as Lua patterns, and the emote clip folder they play.",
        "local _, ns = ...;",
        "ns.EMOTE_PATTERNS = {",
    ]
    for locale in LOCALES:
        seen = {}
        rows = []
        for row in fetch("EmotesTextData", locale):
            emote = EMOTES.get(names.get(row["EmotesTextID"]))
            text = row["Text_lang"].strip()
            if not emote or not text:
                continue
            key = pattern(text)
            if seen.get(key, emote) != emote:
                print(f"{locale}: {text!r} fits two emotes, skipped")
                continue
            if key not in seen:
                seen[key] = emote
                rows.append((key, emote))
        lines.append(f"\t{locale} = {{")
        for key, emote in rows:
            lines.append(f"\t\t{{ {lua_string(key)}, \"{emote}\" }},")
        lines.append("\t},")
        print(f"{locale}: {len(rows)} patterns")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
